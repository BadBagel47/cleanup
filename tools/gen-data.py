#!/usr/bin/env python3
"""Generates js/charnames.js and js/entities.js.

charnames.js: Unicode character names for the ranges this tool is likely to
flag, taken from Python's unicodedata (Unicode Character Database).
entities.js: the named HTML entities (HTML 4 set) with their code points.

Run from the repo root:  python3 tools/gen-data.py
"""
import unicodedata
from html.entities import name2codepoint

RANGES = [
    (0x0020, 0x024F),    # Basic Latin .. Latin Extended-B
    (0x0250, 0x036F),    # IPA, modifiers, combining diacritics
    (0x0370, 0x052F),    # Greek, Cyrillic
    (0x0590, 0x06FF),    # Hebrew, Arabic (marks and format characters)
    (0x1680, 0x1680),
    (0x180B, 0x180F),
    (0x1AB0, 0x1AFF),
    (0x1D00, 0x1DFF),    # phonetic extensions (small capitals), combining
    (0x1E00, 0x1EFF),    # Latin Extended Additional
    (0x2000, 0x2BFF),    # punctuation .. symbols, arrows, dingbats
    (0x2E00, 0x2E7F),
    (0x3000, 0x303F),
    (0x3164, 0x3164),
    (0xA720, 0xA7FF),
    (0xFB00, 0xFB4F),
    (0xFE00, 0xFE0F),
    (0xFE20, 0xFE2F),
    (0xFE50, 0xFE6F),
    (0xFEFF, 0xFEFF),
    (0xFF00, 0xFFEF),
    (0xFFF9, 0xFFFD),
    (0x1D400, 0x1D7FF),  # mathematical alphanumerics
    (0x1F000, 0x1FAFF),  # emoji and pictographs
    (0xE0001, 0xE007F),  # tags
]

C0 = """NULL|START OF HEADING|START OF TEXT|END OF TEXT|END OF TRANSMISSION|ENQUIRY|ACKNOWLEDGE|ALERT|BACKSPACE|CHARACTER TABULATION|LINE FEED|LINE TABULATION|FORM FEED|CARRIAGE RETURN|SHIFT OUT|SHIFT IN|DATA LINK ESCAPE|DEVICE CONTROL ONE|DEVICE CONTROL TWO|DEVICE CONTROL THREE|DEVICE CONTROL FOUR|NEGATIVE ACKNOWLEDGE|SYNCHRONOUS IDLE|END OF TRANSMISSION BLOCK|CANCEL|END OF MEDIUM|SUBSTITUTE|ESCAPE|INFORMATION SEPARATOR FOUR|INFORMATION SEPARATOR THREE|INFORMATION SEPARATOR TWO|INFORMATION SEPARATOR ONE""".split("|")
C1 = """PADDING CHARACTER|HIGH OCTET PRESET|BREAK PERMITTED HERE|NO BREAK HERE|INDEX|NEXT LINE|START OF SELECTED AREA|END OF SELECTED AREA|CHARACTER TABULATION SET|CHARACTER TABULATION WITH JUSTIFICATION|LINE TABULATION SET|PARTIAL LINE FORWARD|PARTIAL LINE BACKWARD|REVERSE LINE FEED|SINGLE SHIFT TWO|SINGLE SHIFT THREE|DEVICE CONTROL STRING|PRIVATE USE ONE|PRIVATE USE TWO|SET TRANSMIT STATE|CANCEL CHARACTER|MESSAGE WAITING|START OF GUARDED AREA|END OF GUARDED AREA|START OF STRING|SINGLE GRAPHIC CHARACTER INTRODUCER|SINGLE CHARACTER INTRODUCER|CONTROL SEQUENCE INTRODUCER|STRING TERMINATOR|OPERATING SYSTEM COMMAND|PRIVACY MESSAGE|APPLICATION PROGRAM COMMAND""".split("|")

names = {}
for i, n in enumerate(C0):
    names[i] = n
names[0x7F] = "DELETE"
for i, n in enumerate(C1):
    names[0x80 + i] = n

# Check the hand-written control names against the Unicode name aliases.
unverified = []
for cp, n in list(names.items()):
    try:
        if ord(unicodedata.lookup(n)) != cp:
            raise KeyError(n)
    except KeyError:
        unverified.append((hex(cp), n))
# Three C1 controls have no formal alias in the database (figment names).
assert all(cp in ("0x80", "0x81", "0x99") for cp, _ in unverified), unverified

for lo, hi in RANGES:
    for cp in range(lo, hi + 1):
        n = unicodedata.name(chr(cp), None)
        if n:
            names[cp] = n

runs = []
for cp in sorted(names):
    if runs and runs[-1][0] + len(runs[-1][1]) == cp:
        runs[-1][1].append(names[cp])
    else:
        runs.append([cp, [names[cp]]])

with open("js/charnames.js", "w", encoding="utf-8") as f:
    f.write("// Generated by tools/gen-data.py. Do not edit by hand.\n")
    f.write("// Character names from the Unicode Character Database (Unicode %s).\n" % unicodedata.unidata_version)
    f.write("// Copyright (c) Unicode, Inc. Used under the Unicode License v3,\n")
    f.write("// https://www.unicode.org/license.txt\n")
    f.write("// Each entry: [first code point, names of consecutive code points joined by '|'].\n")
    f.write("export const NAME_RUNS = [\n")
    for start, ns in runs:
        f.write('[%d,"%s"],\n' % (start, "|".join(ns)))
    f.write("];\n")

ents = dict(name2codepoint)
ents["apos"] = 39
with open("js/entities.js", "w", encoding="utf-8") as f:
    f.write("// Generated by tools/gen-data.py. Do not edit by hand.\n")
    f.write("// Named HTML entities (HTML 4 set plus apos) as name:codepoint pairs.\n")
    f.write('export const ENTITY_DATA = "%s";\n' % ",".join("%s:%d" % (k, ents[k]) for k in sorted(ents)))

print(len(names), "names in", len(runs), "runs;", len(ents), "entities")
